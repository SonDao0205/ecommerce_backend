CREATE TABLE payments (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id          BIGINT        NOT NULL,
  payment_method_id BIGINT        NOT NULL,
  amount            DECIMAL(15,2) NOT NULL,
  status            VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
