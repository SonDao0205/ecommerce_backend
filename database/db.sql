CREATE TABLE products (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
  shop_id       BIGINT        NOT NULL,
  category_id   BIGINT        NOT NULL,
  brand_id      BIGINT        NULL,
  name          VARCHAR(255)  NOT NULL,
  slug          VARCHAR(300)  NOT NULL,
  description   TEXT          NULL,
  thumbnail_url VARCHAR(500)  NULL,
  price         DECIMAL(15,2) NOT NULL DEFAULT 0,
  sold_count    INTEGER       NOT NULL DEFAULT 0,
  rating_avg    DECIMAL(3,2)  NOT NULL DEFAULT 0,
  rating_count  INTEGER       NOT NULL DEFAULT 0,
  status        VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
  reject_reason VARCHAR(500)  NULL,
  is_deleted    SMALLINT      NOT NULL DEFAULT 0,
  created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_products_slug UNIQUE (slug),
  CONSTRAINT fk_products_shop     FOREIGN KEY (shop_id)     REFERENCES shops (id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
  CONSTRAINT fk_products_brand    FOREIGN KEY (brand_id)    REFERENCES brands (id),
  CONSTRAINT chk_products_status CHECK (status IN ('DRAFT','PENDING','ACTIVE','HIDDEN','REJECTED'))
);
CREATE INDEX idx_products_shop     ON products (shop_id);
CREATE INDEX idx_products_category ON products (category_id, status, is_deleted);
CREATE INDEX idx_products_brand    ON products (brand_id);
CREATE INDEX idx_products_price    ON products (price);
CREATE INDEX idx_products_sold     ON products (sold_count);
-- FULLTEXT KEY của MySQL -> GIN index + tsvector
CREATE INDEX ft_products_name ON products USING GIN (to_tsvector('simple', name));

